use crate::shape::{Model, Parser, Shape};
use crate::{
    GenerationError, ObservableModel, ObservableResource, UnsupportedShape, fail, identifier,
    quote, schema,
};
use std::collections::BTreeSet;
use std::fmt::Write as _;
use studio_json::Value;

const HEADER: &str = "// Generated by studio-contracts from Rust observable metadata; do not edit.\nimport { makeObservable, observableShallow, observableRef, action, runInAction } from 'mobx';\nimport type { components } from './api.ts';\nimport type { DeepReadonly } from '../deepReadonly.ts';\nimport type { ResourceRef } from '../sync/subscriptions/contracts.ts';\nimport type { ResourceSlot, ObservableResourceRuntime } from '../store/index.ts';\nimport { subscriptionKey } from '../sync/subscriptions/contracts.ts';\n";

/// Generate schema-derived private models and public readonly resource facades.
/// The document must have OpenAPI components; no I/O or global state is used.
pub fn render(
    document: &Value,
    metadata: &[ObservableModel],
    resources: &[ObservableResource],
) -> Result<String, GenerationError> {
    let mut parser = Parser::new(document, metadata);
    let mut names = BTreeSet::new();
    for resource in resources {
        crate::metadata::validate(document, resource)?;
        let path = format!("#/resources/{}", resource.kind);
        for name in [&resource.facade, &resource.data] {
            identifier(name, &path)?;
        }
        if !names.insert(resource.facade.clone()) {
            return Err(fail(&path, UnsupportedShape::Identifier));
        }
        let shape = parser.parse(
            schema(document, &resource.data)?,
            &resource.data,
            &format!(
                "DeepReadonly<components['schemas'][{}]>",
                quote(&resource.data)
            ),
            &format!("#/components/schemas/{}", resource.data),
        )?;
        if !matches!(shape, Shape::Object(_)) {
            return Err(fail(&path, UnsupportedShape::Shape));
        }
    }
    for meta in metadata {
        if !parser.models.contains_key(&meta.schema) {
            return Err(fail(
                &format!("#/components/schemas/{}", meta.schema),
                UnsupportedShape::MissingSchema,
            ));
        }
    }
    let mut out = String::from(HEADER);
    let mut brands = BTreeSet::new();
    for resource in resources {
        for arg in &resource.args {
            let path = format!("#/resources/{}/args/{}", resource.kind, arg.name);
            identifier(&arg.name, &path)?;
            if [
                "key",
                "ref",
                "cached",
                "slot",
                "runtime",
                "subscriptionKey",
                "Map",
            ]
            .contains(&arg.name.as_str())
                || arg.name == format!("{}Slots", resource.facade)
                || arg.name == format!("{}Model", resource.data)
                || (0..resource.args.len()).any(|index| arg.name == format!("cache{index}"))
            {
                return Err(fail(&path, UnsupportedShape::Identifier));
            }
            identifier(&arg.brand, &resource.kind)?;
            if brands.insert(arg.brand.clone()) {
                let brand = &arg.brand;
                let constructor = lower_first(brand);
                writeln!(out,"declare const {constructor}Brand: unique symbol;\nexport type {brand} = string & {{ readonly [{constructor}Brand]: true }};\nexport function {constructor}(value: string): {brand};\nexport function {constructor}(value: string): string {{ return value; }}").expect("string");
            }
        }
    }
    for model in parser.models.values() {
        emit_model(&mut out, model, &parser);
    }
    for union in parser.unions.values() {
        emit_union(&mut out, union);
    }
    for model in metadata {
        if !resources
            .iter()
            .any(|resource| resource.data == model.schema)
        {
            writeln!(
                out,
                "export type {} = DeepReadonly<components['schemas'][{}]>;",
                model.schema,
                quote(&model.schema)
            )
            .expect("string");
        }
    }
    for resource in resources {
        writeln!(
            out,
            "export type {} = DeepReadonly<components['schemas'][{}]>;",
            resource.data,
            quote(&resource.data)
        )
        .expect("string");
    }
    for resource in resources {
        let data = &resource.data;
        let model = &parser.models[data];
        if let Some(field) = model
            .fields
            .iter()
            .find(|field| !matches!(field.shape, Shape::Array(_)) || field.optional)
        {
            return Err(fail(
                &format!("#/components/schemas/{data}/properties/{}", field.name),
                UnsupportedShape::Shape,
            ));
        }
        let initial = model
            .fields
            .iter()
            .map(|field| format!("{}: []", field.name))
            .collect::<Vec<_>>()
            .join(", ");
        let mut facade = resource.facade.chars();
        let mirror = format!(
            "create{}{}Mirror",
            facade.next().expect("facade").to_ascii_uppercase(),
            facade.as_str()
        );
        writeln!(out,"export function {mirror}(): {{ readonly current: {data}; apply(dto: {data}): void }} {{ const model = new {data}Model({{ {initial} }}); return {{ get current(): {data} {{ return model; }}, apply(dto: {data}): void {{ runInAction(() => {{ model.apply(dto); }}); }} }}; }}").expect("string");
    }
    out.push_str("export interface ObservableResources {\n");
    for resource in resources {
        writeln!(
            out,
            "{}({}): ResourceSlot<{}>;",
            resource.facade,
            args(resource),
            resource.data
        )
        .expect("string");
    }
    out.push_str("}\nexport function createObservableResources(runtime: ObservableResourceRuntime): ObservableResources {\n");
    for resource in resources {
        if resource.args.is_empty() {
            writeln!(
                out,
                "let {}Slot: ResourceSlot<{}> | undefined;",
                resource.facade, resource.data
            )
            .expect("string");
        } else {
            writeln!(
                out,
                "const {}Slots = new {}();",
                resource.facade,
                arg_map_type(resource, 0)
            )
            .expect("string");
        }
    }
    out.push_str("return {\n");
    for resource in resources {
        let facade = &resource.facade;
        let data = &resource.data;
        writeln!(out, "{facade}({}) {{", args(resource)).expect("string");
        if resource.args.is_empty() {
            writeln!(out, "if ({facade}Slot !== undefined) return {facade}Slot;").expect("string");
        } else {
            let lookup = resource
                .args
                .iter()
                .map(|arg| format!("get({})", arg.name))
                .collect::<Vec<_>>()
                .join("?.");
            writeln!(
                out,
                "const cached = {facade}Slots.{lookup};\nif (cached !== undefined) return cached;"
            )
            .expect("string");
        }
        let reference = format!(
            "{{ kind: {}{} }}",
            quote(&resource.kind),
            resource
                .args
                .iter()
                .map(|a| format!(", {}", a.name))
                .collect::<String>()
        );
        // The canonical subscription key owner is shared with transport.
        writeln!(out,"const ref: Extract<ResourceRef, {{kind: {}}}> = {reference};\nconst key = subscriptionKey(ref);",quote(&resource.kind)).expect("string");
        if resource.args.is_empty() {
            writeln!(out,"return {facade}Slot = runtime.slot({{ key, ref, create: (dto) => new {data}Model(dto), apply: (data, dto) => {{ data.apply(dto); }} }});").expect("string");
        } else {
            writeln!(out,"const slot = runtime.slot({{ key, ref, create: (dto) => new {data}Model(dto), apply: (data, dto) => {{ data.apply(dto); }} }});").expect("string");
            let mut parent = format!("{facade}Slots");
            for (index, arg) in resource.args.iter().enumerate() {
                if index + 1 == resource.args.len() {
                    writeln!(out, "{parent}.set({}, slot);", arg.name).expect("string");
                } else {
                    let child = format!("cache{index}");
                    writeln!(out,"let {child} = {parent}.get({});\nif ({child} === undefined) {{ {child} = new {}(); {parent}.set({}, {child}); }}",arg.name,arg_map_type(resource,index+1),arg.name).expect("string");
                    parent = child;
                }
            }
            out.push_str("return slot;\n");
        }
        out.push_str("},\n");
    }
    out.push_str("};\n}\n");
    Ok(out)
}
fn arg_map_type(resource: &ObservableResource, start: usize) -> String {
    resource.args[start..]
        .iter()
        .rev()
        .fold(format!("ResourceSlot<{}>", resource.data), |value, arg| {
            format!("Map<{}, {value}>", arg.brand)
        })
}
fn lower_first(value: &str) -> String {
    let mut chars = value.chars();
    format!(
        "{}{}",
        chars.next().expect("identifier").to_ascii_lowercase(),
        chars.as_str()
    )
}
fn args(resource: &ObservableResource) -> String {
    resource
        .args
        .iter()
        .map(|a| format!("{}: {}", a.name, a.brand))
        .collect::<Vec<_>>()
        .join(", ")
}
fn ty(shape: &Shape, dto: &str) -> String {
    match shape {
        Shape::Leaf => dto.into(),
        Shape::Object(name) => format!("{name}Model"),
        Shape::Array(item) => format!("({})[]", ty(item, &format!("NonNullable<{dto}>[number]"))),
        Shape::Nullable(item) => format!("{} | null", ty(item, &format!("NonNullable<{dto}>"))),
        Shape::Union { name, .. } => format!("{name}Model"),
    }
}
fn create(shape: &Shape, value: &str, parser: &Parser<'_>) -> String {
    match shape {
        Shape::Leaf => value.into(),
        Shape::Object(name) => format!("new {name}Model({value})"),
        Shape::Array(item) => {
            if let Shape::Object(name) = item.as_ref()
                && parser.models[name].identity.is_some()
            {
                return format!("reconcile{name}([], {value})");
            }
            format!("{value}.map((item) => {})", create(item, "item", parser))
        }
        Shape::Nullable(item) => format!(
            "({value} === null ? null : {})",
            create(item, value, parser)
        ),
        Shape::Union { name, .. } => format!("create{name}({value})"),
    }
}
fn equal(shape: &Shape, left: &str, right: &str, parser: &Parser<'_>, depth: usize) -> String {
    match shape {
        Shape::Leaf => format!("{left} === {right}"),
        Shape::Object(name) => {
            let expressions = parser.models[name].fields.iter().map(|field| {
                let left=format!("{left}.{}",field.name); let right=format!("{right}.{}",field.name);
                let expression=if field.opaque { format!("Object.is({left}, {right})") } else { equal(&field.shape,&left,&right,parser,depth) };
                if field.optional { format!("({left} === undefined || {right} === undefined ? {left} === {right} : {expression})") } else { expression }
            }).collect::<Vec<_>>();
            if expressions.is_empty() {
                "true".into()
            } else {
                format!("({})", expressions.join(" && "))
            }
        }
        Shape::Array(item) => {
            let l = format!("leftItem{depth}");
            let r = format!("rightItem{depth}");
            format!(
                "({left}.length === {right}.length && {left}.every(({l}, index) => {{ const {r} = {right}?.[index]; return {r} !== undefined && {}; }}))",
                equal(item, &l, &r, parser, depth + 1)
            )
        }
        Shape::Nullable(item) => format!(
            "({left} === null || {right} === null ? {left} === {right} : {})",
            equal(item, left, right, parser, depth)
        ),
        Shape::Union { tag, variants, .. } => format!(
            "({})",
            variants
                .iter()
                .map(|(value, name)| format!(
                    "({left}.{tag} === {} && {right}.{tag} === {} && {})",
                    quote(value),
                    quote(value),
                    equal(&Shape::Object(name.clone()), left, right, parser, depth)
                ))
                .collect::<Vec<_>>()
                .join(" || ")
        ),
    }
}
fn apply(shape: &Shape, left: &str, right: &str, parser: &Parser<'_>) -> String {
    match shape {
        Shape::Leaf => right.into(),
        Shape::Object(_) => format!("{left}.apply({right})"),
        Shape::Nullable(item) => format!(
            "({right} === null ? null : {left} === null ? {} : {})",
            create(item, right, parser),
            apply(item, left, right, parser)
        ),
        Shape::Array(item) => {
            if let Shape::Object(name) = item.as_ref()
                && parser.models[name].identity.is_some()
            {
                return format!("reconcile{name}({left}, {right})");
            }
            format!(
                "({} ? {left} : {})",
                equal(shape, left, right, parser, 0),
                create(shape, right, parser)
            )
        }
        Shape::Union { name, .. } => format!("update{name}({left}, {right})"),
    }
}
fn emit_model(out: &mut String, model: &Model, parser: &Parser<'_>) {
    let name = &model.name;
    let dto = &model.dto;
    writeln!(out, "type {name}Dto = {dto};\nclass {name}Model {{").expect("string");
    for f in &model.fields {
        writeln!(
            out,
            "{}: {}{};",
            f.name,
            ty(&f.shape, &f.ty),
            if f.optional { " | undefined" } else { "" }
        )
        .expect("string");
    }
    writeln!(out, "constructor(dto: {name}Dto) {{").expect("string");
    for f in &model.fields {
        let value = format!("dto.{}", f.name);
        let expression = create(&f.shape, &value, parser);
        writeln!(
            out,
            "this.{} = {};",
            f.name,
            if f.optional {
                format!("{value} === undefined ? undefined : {expression}")
            } else {
                expression
            }
        )
        .expect("string");
    }
    out.push_str("makeObservable(this, {\n");
    for f in &model.fields {
        let mut shape = &f.shape;
        if let Shape::Nullable(item) = shape {
            shape = item;
        }
        let ordered = matches!(shape, Shape::Array(item) if matches!(item.as_ref(), Shape::Object(name) if parser.models[name].identity.is_some() && parser.models[name].ordered_by.is_some()));
        let annotation = if ordered && !f.opaque {
            "observableShallow"
        } else {
            "observableRef"
        };
        writeln!(out, "{}: {annotation},", f.name).expect("string");
    }
    out.push_str("apply: action,\n});\n}\n");
    writeln!(out, "apply(dto: {name}Dto): this {{").expect("string");
    for f in &model.fields {
        let left = format!("this.{}", f.name);
        let right = format!("dto.{}", f.name);
        let expression = apply(&f.shape, &left, &right, parser);
        let expression = if f.optional {
            format!(
                "{right} === undefined ? undefined : {left} === undefined ? {} : {expression}",
                create(&f.shape, &right, parser)
            )
        } else {
            expression
        };
        writeln!(
            out,
            "{{ const next = {expression}; if ({left} !== next) {left} = next; }}"
        )
        .expect("string");
    }
    out.push_str("return this;\n}\n}\n");
    if let Some(id) = &model.identity {
        if let Some(order) = &model.ordered_by {
            writeln!(out, "function reconcile{name}(data: {name}Model[], dto: readonly {name}Dto[]): {name}Model[] {{
const incoming = new Map<string, {name}Dto>();
for (const item of dto) {{ if (incoming.has(item.{id})) throw new Error('Duplicate identity in {name}'); incoming.set(item.{id}, item); }}
if (data.length === 0 && dto.length > 0) {{
const rows = dto.map((item) => new {name}Model(item)).sort((left, right) => left.{order} < right.{order} ? -1 : left.{order} > right.{order} ? 1 : left.{id} < right.{id} ? -1 : 1);
data.push(...rows);
return data;
}}
const previous = new Map(data.map((item) => [item.{id}, item]));
for (let index = data.length - 1; index >= 0; index -= 1) {{
const row = data[index]; if (row === undefined) throw new Error('Invalid removal index');
const item = incoming.get(row.{id});
if (item === undefined || row.{order} !== item.{order}) data.splice(index, 1);
}}
for (const item of dto) {{
const existing = previous.get(item.{id});
if (existing !== undefined && existing.{order} === item.{order}) {{ existing.apply(item); continue; }}
const row = existing === undefined ? new {name}Model(item) : existing.apply(item);
let low = 0; let high = data.length;
while (low < high) {{ const middle = Math.floor((low + high) / 2); const candidate = data[middle]; if (candidate === undefined) throw new Error('Invalid insertion index'); if (candidate.{order} < row.{order} || (candidate.{order} === row.{order} && candidate.{id} < row.{id})) low = middle + 1; else high = middle; }}
data.splice(low, 0, row);
}}
return data;
}}").expect("string");
            return;
        }
        writeln!(out,"function reconcile{name}(data: {name}Model[], dto: readonly {name}Dto[]): {name}Model[] {{\nconst ids = new Set<string>();\nfor (const item of dto) {{ if (ids.has(item.{id})) throw new Error('Duplicate identity in {name}'); ids.add(item.{id}); }}\nconst previous = new Map(data.map((item) => [item.{id}, item]));\nconst next: {name}Model[] = [];\nfor (const item of dto) {{\nconst existing = previous.get(item.{id});\nconst row = existing === undefined ? new {name}Model(item) : existing.apply(item);").expect("string");
        out.push_str("next.push(row);\n");
        out.push_str("}\nreturn data.length === next.length && data.every((item, index) => item === next[index]) ? data : next;\n}\n");
    }
}
fn emit_union(out: &mut String, union: &Shape) {
    let Shape::Union {
        name,
        dto,
        tag,
        variants,
    } = union
    else {
        return;
    };
    writeln!(
        out,
        "type {name}Model = {};",
        variants
            .iter()
            .map(|(_, n)| format!("{n}Model"))
            .collect::<Vec<_>>()
            .join(" | ")
    )
    .expect("string");
    writeln!(
        out,
        "function create{name}(dto: {dto}): {name}Model {{ switch (dto.{tag}) {{"
    )
    .expect("string");
    for (tag, variant) in variants {
        writeln!(out, "case {}: return new {variant}Model(dto);", quote(tag)).expect("string");
    }
    out.push_str("} }\n");
    writeln!(
        out,
        "function update{name}(data: {name}Model, dto: {dto}): {name}Model {{ switch (dto.{tag}) {{"
    )
    .expect("string");
    for (value, variant) in variants {
        writeln!(
            out,
            "case {}: return data.{tag} === {} ? data.apply(dto) : new {variant}Model(dto);",
            quote(value),
            quote(value)
        )
        .expect("string");
    }
    out.push_str("} }\n");
}
