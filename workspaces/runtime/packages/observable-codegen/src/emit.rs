use crate::shape::{Model, Parser, Shape};
use crate::{
    GenerationError, ObservableModel, ObservableResource, UnsupportedShape, fail, identifier,
    quote, schema,
};
use std::collections::BTreeSet;
use std::fmt::Write as _;
use studio_json::Value;

const HEADER: &str = "// Generated by studio-contracts from Rust observable metadata; do not edit.\nimport { makeObservable, observableRef, action } from 'mobx';\nimport type { components } from './api.ts';\nimport type { DeepReadonly } from '../deepReadonly.ts';\nimport type { ResourceRef } from '../sync/subscriptions/contracts.ts';\nimport type { ResourceSlot, ObservableResourceRuntime } from '../store/index.ts';\nimport { subscriptionKey } from '../sync/subscriptions/contracts.ts';\n";

/// Generate schema-derived private models and public readonly resource facades.
/// The document must have OpenAPI components; no I/O or global state is used.
pub fn render(
    document: &Value,
    metadata: &[ObservableModel],
    resources: &[ObservableResource],
) -> Result<String, GenerationError> {
    let mut parser = Parser::new(document, metadata);
    let mut names = BTreeSet::new();
    let mut roots = vec![];
    for resource in resources {
        crate::metadata::validate(document, resource)?;
        let path = format!("#/resources/{}", resource.kind);
        for name in [&resource.facade, &resource.data] {
            identifier(name, &path)?;
        }
        if !names.insert(resource.facade.clone()) {
            return Err(fail(&path, UnsupportedShape::Identifier));
        }
        let shape = parser.parse(
            schema(document, &resource.data)?,
            &resource.data,
            &format!(
                "DeepReadonly<components['schemas'][{}]>",
                quote(&resource.data)
            ),
            &format!("#/components/schemas/{}", resource.data),
        )?;
        if !matches!(shape, Shape::Object(_)) {
            return Err(fail(&path, UnsupportedShape::Shape));
        }
        roots.push(shape);
    }
    for meta in metadata {
        if !parser.models.contains_key(&meta.schema) {
            return Err(fail(
                &format!("#/components/schemas/{}", meta.schema),
                UnsupportedShape::MissingSchema,
            ));
        }
    }
    let mut out = String::from(HEADER);
    let mut brands = BTreeSet::new();
    for resource in resources {
        for arg in &resource.args {
            identifier(&arg.name, &resource.kind)?;
            identifier(&arg.brand, &resource.kind)?;
            if brands.insert(arg.brand.clone()) {
                let brand = &arg.brand;
                let constructor = lower_first(brand);
                writeln!(out,"declare const {constructor}Brand: unique symbol;\nexport type {brand} = string & {{ readonly [{constructor}Brand]: true }};\nexport function {constructor}(value: string): {brand};\nexport function {constructor}(value: string): string {{ return value; }}").expect("string");
            }
        }
    }
    for model in parser.models.values() {
        emit_model(&mut out, model, &parser);
    }
    for union in parser.unions.values() {
        emit_union(&mut out, union);
    }
    for model in metadata {
        if !resources
            .iter()
            .any(|resource| resource.data == model.schema)
        {
            writeln!(
                out,
                "export type {} = DeepReadonly<components['schemas'][{}]>;",
                model.schema,
                quote(&model.schema)
            )
            .expect("string");
        }
    }
    for resource in resources {
        writeln!(
            out,
            "export type {} = DeepReadonly<components['schemas'][{}]>;",
            resource.data,
            quote(&resource.data)
        )
        .expect("string");
    }
    out.push_str("export interface ObservableResources {\n");
    for resource in resources {
        writeln!(
            out,
            "{}({}): ResourceSlot<{}>;",
            resource.facade,
            args(resource),
            resource.data
        )
        .expect("string");
    }
    out.push_str("}\nexport function createObservableResources(runtime: ObservableResourceRuntime): ObservableResources {\n");
    for resource in resources {
        if resource.args.is_empty() {
            writeln!(
                out,
                "let {}Slot: ResourceSlot<{}> | undefined;",
                resource.facade, resource.data
            )
            .expect("string");
        } else {
            writeln!(
                out,
                "const {}Slots = new Map<string, ResourceSlot<{}>>();",
                resource.facade, resource.data
            )
            .expect("string");
        }
    }
    out.push_str("return {\n");
    for resource in resources {
        let facade = &resource.facade;
        let data = &resource.data;
        writeln!(out, "{facade}({}) {{", args(resource)).expect("string");
        let reference = format!(
            "{{ kind: {}{} }}",
            quote(&resource.kind),
            resource
                .args
                .iter()
                .map(|a| format!(", {}", a.name))
                .collect::<String>()
        );
        // The canonical subscription key owner is shared with transport.
        writeln!(out,"const ref: Extract<ResourceRef, {{kind: {}}}> = {reference};\nconst key = subscriptionKey(ref);",quote(&resource.kind)).expect("string");
        if resource.args.is_empty() {
            writeln!(out,"return {facade}Slot ??= runtime.slot({{ key, ref, create: (dto) => new {data}Model(dto), apply: (data, dto) => {{ data.apply(dto); }} }});").expect("string");
        } else {
            writeln!(out,"const cached = {facade}Slots.get(key);\nif (cached) return cached;\nconst slot = runtime.slot({{ key, ref, create: (dto) => new {data}Model(dto), apply: (data, dto) => {{ data.apply(dto); }} }});\n{facade}Slots.set(key, slot);\nreturn slot;").expect("string");
        }
        out.push_str("},\n");
    }
    out.push_str("};\n}\n");
    Ok(out)
}
fn lower_first(value: &str) -> String {
    let mut chars = value.chars();
    format!(
        "{}{}",
        chars.next().expect("identifier").to_ascii_lowercase(),
        chars.as_str()
    )
}
fn args(resource: &ObservableResource) -> String {
    resource
        .args
        .iter()
        .map(|a| format!("{}: {}", a.name, a.brand))
        .collect::<Vec<_>>()
        .join(", ")
}
fn ty(shape: &Shape, dto: &str) -> String {
    match shape {
        Shape::Leaf => dto.into(),
        Shape::Object(name) => format!("{name}Model"),
        Shape::Array(item) => format!("({})[]", ty(item, &format!("NonNullable<{dto}>[number]"))),
        Shape::Nullable(item) => format!("{} | null", ty(item, &format!("NonNullable<{dto}>"))),
        Shape::Union { name, .. } => format!("{name}Model"),
    }
}
fn create(shape: &Shape, value: &str) -> String {
    match shape {
        Shape::Leaf => value.into(),
        Shape::Object(name) => format!("new {name}Model({value})"),
        Shape::Array(item) => match item.as_ref() {
            Shape::Object(name) => format!("create{name}Array({value})"),
            Shape::Leaf | Shape::Array(_) | Shape::Nullable(_) | Shape::Union { .. } => {
                format!("{value}.map((item) => {})", create(item, "item"))
            }
        },
        Shape::Nullable(item) => format!("({value} === null ? null : {})", create(item, value)),
        Shape::Union { name, .. } => format!("create{name}({value})"),
    }
}
fn equal(shape: &Shape, left: &str, right: &str, opaque: bool) -> String {
    if opaque {
        return format!("Object.is({left}, {right})");
    }
    match shape {
        Shape::Leaf => format!("{left} === {right}"),
        Shape::Object(name) => format!("equal{name}({left}, {right})"),
        Shape::Array(item) => format!(
            "({left}.length === {right}.length && {left}.every((item, index) => {{ const other = {right}[index]; return other !== undefined && {}; }}))",
            equal(item, "item", "other", false)
        ),
        Shape::Nullable(item) => format!(
            "({left} === null || {right} === null ? {left} === {right} : {})",
            equal(item, left, right, false)
        ),
        Shape::Union { name, .. } => format!("equal{name}({left}, {right})"),
    }
}
fn apply(shape: &Shape, left: &str, right: &str, parser: &Parser<'_>) -> String {
    match shape {
        Shape::Leaf => right.into(),
        Shape::Object(name) => format!("update{name}({left}, {right})"),
        Shape::Nullable(item) => format!(
            "({right} === null ? null : {left} === null ? {} : {})",
            create(item, right),
            apply(item, left, right, parser)
        ),
        Shape::Array(item) => {
            if let Shape::Object(name) = item.as_ref()
                && parser.models[name].identity.is_some()
            {
                return format!("reconcile{name}({left}, {right})");
            }
            format!(
                "({} ? {left} : {})",
                equal(shape, left, right, false),
                create(shape, right)
            )
        }
        Shape::Union { name, .. } => format!("update{name}({left}, {right})"),
    }
}
fn emit_model(out: &mut String, model: &Model, parser: &Parser<'_>) {
    let name = &model.name;
    let dto = &model.dto;
    writeln!(out, "type {name}Dto = {dto};\nclass {name}Model {{").expect("string");
    for f in &model.fields {
        writeln!(
            out,
            "{}: {}{};",
            f.name,
            ty(&f.shape, &f.ty),
            if f.optional { " | undefined" } else { "" }
        )
        .expect("string");
    }
    writeln!(out, "constructor(dto: {name}Dto) {{").expect("string");
    for f in &model.fields {
        let value = format!("dto.{}", f.name);
        let expression = create(&f.shape, &value);
        writeln!(
            out,
            "this.{} = {};",
            f.name,
            if f.optional {
                format!("{value} === undefined ? undefined : {expression}")
            } else {
                expression
            }
        )
        .expect("string");
    }
    out.push_str("makeObservable(this, {\n");
    for f in &model.fields {
        writeln!(out, "{}: observableRef,", f.name).expect("string");
    }
    out.push_str("apply: action,\n});\n}\n");
    writeln!(out, "apply(dto: {name}Dto): void {{").expect("string");
    for f in &model.fields {
        let left = format!("this.{}", f.name);
        let right = format!("dto.{}", f.name);
        let expression = apply(&f.shape, &left, &right, parser);
        let expression = if f.optional {
            format!(
                "{right} === undefined ? undefined : {left} === undefined ? {} : {expression}",
                create(&f.shape, &right)
            )
        } else {
            expression
        };
        writeln!(
            out,
            "{{ const next = {expression}; if ({left} !== next) {left} = next; }}"
        )
        .expect("string");
    }
    writeln!(out,"}}\n}}\nfunction update{name}(data: {name}Model, dto: {name}Dto): {name}Model {{ data.apply(dto); return data; }}").expect("string");
    let equality=model.fields.iter().map(|f| {
        let left=format!("left.{}",f.name);let right=format!("right.{}",f.name);let expression=equal(&f.shape,&left,&right,f.opaque);
        if f.optional {format!("({left} === undefined || {right} === undefined ? {left} === {right} : {expression})")} else {expression}
    }).collect::<Vec<_>>().join(" && ");
    writeln!(
        out,
        "function equal{name}(left: {name}Dto, right: {name}Dto): boolean {{ return {}; }}",
        if equality.is_empty() {
            "true"
        } else {
            &equality
        }
    )
    .expect("string");
    writeln!(
        out,
        "function create{name}Array(dto: readonly {name}Dto[]): {name}Model[] {{ return {}; }}",
        if model.identity.is_some() {
            format!("reconcile{name}([], dto)")
        } else {
            format!("dto.map((item) => new {name}Model(item))")
        }
    )
    .expect("string");
    if let Some(id) = &model.identity {
        writeln!(out,"function reconcile{name}(data: {name}Model[], dto: readonly {name}Dto[]): {name}Model[] {{\nconst ids = new Set<string>();\nfor (const item of dto) {{ if (ids.has(item.{id})) throw new Error('Duplicate identity in {name}'); ids.add(item.{id}); }}\nconst previous = new Map(data.map((item) => [item.{id}, item]));\nconst next: {name}Model[] = [];\nfor (const item of dto) {{\nconst existing = previous.get(item.{id});\nconst row = existing === undefined ? new {name}Model(item) : update{name}(existing, item);").expect("string");
        if let Some(order) = &model.ordered_by {
            writeln!(out,"let low = 0; let high = next.length;\nwhile (low < high) {{ const middle = Math.floor((low + high) / 2); const candidate = next[middle]; if (candidate === undefined) throw new Error('Invalid insertion index'); if (candidate.{order} < row.{order}) low = middle + 1; else high = middle; }}\nnext.splice(low, 0, row);").expect("string");
        } else {
            out.push_str("next.push(row);\n");
        }
        out.push_str("}\nreturn data.length === next.length && data.every((item, index) => item === next[index]) ? data : next;\n}\n");
    }
}
fn emit_union(out: &mut String, union: &Shape) {
    let Shape::Union {
        name,
        dto,
        tag,
        variants,
    } = union
    else {
        return;
    };
    writeln!(
        out,
        "type {name}Model = {};",
        variants
            .iter()
            .map(|(_, n)| format!("{n}Model"))
            .collect::<Vec<_>>()
            .join(" | ")
    )
    .expect("string");
    writeln!(
        out,
        "function create{name}(dto: {dto}): {name}Model {{ switch (dto.{tag}) {{"
    )
    .expect("string");
    for (tag, variant) in variants {
        writeln!(out, "case {}: return new {variant}Model(dto);", quote(tag)).expect("string");
    }
    out.push_str("} }\n");
    writeln!(
        out,
        "function update{name}(data: {name}Model, dto: {dto}): {name}Model {{ switch (dto.{tag}) {{"
    )
    .expect("string");
    for (value, variant) in variants {
        writeln!(out,"case {}: return data.{tag} === {} ? update{variant}(data, dto) : new {variant}Model(dto);",quote(value),quote(value)).expect("string");
    }
    out.push_str("} }\n");
    writeln!(
        out,
        "function equal{name}(left: {dto}, right: {dto}): boolean {{ switch (left.{tag}) {{"
    )
    .expect("string");
    for (value, variant) in variants {
        writeln!(
            out,
            "case {}: return right.{tag} === {} && equal{variant}(left, right);",
            quote(value),
            quote(value)
        )
        .expect("string");
    }
    out.push_str("} }\n");
}
