//! Collection inventory derives from the same Rust-owned payload union as transport.
use crate::{GenerationError, UnsupportedShape, fail, identifier, quote, schema};
use std::collections::BTreeSet;
use std::fmt::Write as _;
use studio_json::Value;

pub fn render_entity_collections(document: &Value) -> Result<String, GenerationError> {
    let path = "#/components/schemas/SyncEntityPayload";
    let variants = schema(document, "SyncEntityPayload")?["oneOf"]
        .as_array()
        .ok_or_else(|| fail(path, UnsupportedShape::Union))?;
    let mut names = BTreeSet::new();
    for variant in variants {
        let variant = if let Some(reference) = variant["$ref"].as_str() {
            schema(
                document,
                reference
                    .strip_prefix("#/components/schemas/")
                    .ok_or_else(|| fail(path, UnsupportedShape::MissingSchema))?,
            )?
        } else {
            variant
        };
        let name = variant["properties"]["collection"]["const"]
            .as_str()
            .ok_or_else(|| fail(path, UnsupportedShape::Union))?;
        identifier(name, path)?;
        if !names.insert(name) {
            return Err(fail(path, UnsupportedShape::Union));
        }
    }
    let mut out = String::from(
        "// Generated by studio-contracts from Rust entity metadata; do not edit.\nimport type { components } from './api.ts';\ntype Payload = components['schemas']['SyncEntityPayload'];\nexport const ENTITY_COLLECTIONS = [\n",
    );
    for name in &names {
        writeln!(out, "{},", quote(name)).expect("string");
    }
    out.push_str("] as const satisfies readonly Payload['collection'][];\nexport type EntityCollection = Payload['collection'];\nexport type EntityFor<C extends EntityCollection> = Extract<Payload, { collection: C }>['value'];\nexport type EntityValues = { [C in EntityCollection]: Map<string, EntityFor<C>> };\nexport function emptyEntityValues(): EntityValues { return {\n");
    for name in &names {
        writeln!(out, "{}: new Map(),", quote(name)).expect("string");
    }
    out.push_str("}; }\nexport function setEntityValue(values: EntityValues, entity: Payload): void { switch (entity.collection) {\n");
    for name in &names {
        writeln!(
            out,
            "case {}: values.{}.set(entity.id, entity.value); break;",
            quote(name),
            name
        )
        .expect("string");
    }
    out.push_str("default: { const exhaustive: never = entity; return exhaustive; }\n} }\n");
    Ok(out)
}
